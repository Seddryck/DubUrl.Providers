    private static ConnectionUrl OwnerUrl => new ConnectionUrl(DatabricksWarehouse.Url).WithAuthentication(DatabricksWarehouse.Authentication);

    [Test]
    public Task ColumnTagsAndCommentsRoundTripThroughDocuments()
    {
        var url = OwnerUrl;
        return SparkSchemaQa.WithScratchAsync(url, async (connection, catalog, schema) =>
        {
            var renderer = new SchemaScriptRenderer(url.Dialect);
            var column = new Column("id", DbType.Int32, description: "Owner's description")
            { Annotations = new Dictionary<string, string> { ["duburl_qa_owner"] = "analytics" } };
            var reader = new DatabricksMetadataReader();

            async Task<Table> Discover(string name)
            {
                var result = await new SchemaInspector().InspectAsync(connection, reader, new()
                {
                    Tables = [new(name, schema, Catalog: catalog)],
                    Features = [SchemaFeature.Tables, SchemaFeature.Columns, SchemaFeature.Comments, SchemaFeature.ColumnAnnotations]
                });
                Assert.That(result.IsComplete, Is.True, string.Join(", ", result.Diagnostics.Select(item => item.Message)));
                return result.Schema!.Tables.Values.Single();
            }

            var source = new Table(new DatabaseObjectName("source_items", schema, null, catalog), [column]);
            foreach (var command in renderer.Plan(new([source])))
                SparkSchemaQa.Execute(connection, command.CommandText);
            var document = new SchemaDocumentExporter().Map(new([await Discover("source_items")]));
            document.Tables.Single().Identity.Name = "target_items";
            foreach (var command in renderer.Plan(new SchemaDocumentMapper().Map(document)))
                SparkSchemaQa.Execute(connection, command.CommandText);

            var recreated = (await Discover("target_items")).Columns[column.Name];
            Assert.That(recreated.Description, Is.EqualTo(column.Description));
            Assert.That(recreated.Annotations, Is.EquivalentTo(column.Annotations));
        });
    }

    [Test]
    public Task ScopedDiscoveryFollowsReferencesAndReadsCanonicalDefinitions()
    {
        var url = OwnerUrl;
        return SparkSchemaQa.WithScratchAsync(url, async (connection, catalog, schema) =>
        {
            var quote = url.Dialect.SchemaSqlRenderer;
            string Name(string table, string inSchema)
                => quote.RenderObjectName(url.Dialect, catalog, null, inSchema, table);
            var parentSchema = schema + "_parent";
            var parentScope = $"{quote.RenderIdentifier(url.Dialect, catalog)}.{quote.RenderIdentifier(url.Dialect, parentSchema)}";
            var child = Name("child", schema);
            SparkSchemaQa.Execute(connection, $"CREATE SCHEMA {parentScope}");
            try
            {
                var parent = Name("parent", parentSchema);
                SparkSchemaQa.Execute(connection, $"CREATE TABLE {parent} (a INT NOT NULL, b INT NOT NULL, "
                    + "CONSTRAINT parent_pk PRIMARY KEY (b, a)) USING DELTA");
                SparkSchemaQa.Execute(connection, $"""
                    CREATE TABLE {child} (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 20 INCREMENT BY -2),
                        ref_a INT, ref_b INT, omitted INT, explicit_null INT DEFAULT NULL,
                        local_stamp TIMESTAMP_NTZ DEFAULT CAST(current_timestamp() AS TIMESTAMP_NTZ),
                        note STRING, folded STRING GENERATED ALWAYS AS (lower(note)),
                        CONSTRAINT ordered_fk FOREIGN KEY (ref_b, ref_a) REFERENCES {parent} (b, a)
                    ) USING DELTA TBLPROPERTIES ('delta.feature.allowColumnDefaults' = 'supported')
                    """);
                SparkSchemaQa.Execute(connection, $"ALTER TABLE {child} ADD CONSTRAINT ordered_check CHECK (coalesce((ref_b >= 0), true))");
                SparkSchemaQa.Execute(connection, $"ALTER TABLE {child} ADD CONSTRAINT rejects_unknown CHECK (ref_a >= 0)");
                SparkSchemaQa.Execute(connection, $"CREATE TABLE {Name("unselected", schema)} (id BIGINT GENERATED ALWAYS AS IDENTITY) USING DELTA");

                var childIdentity = new MetadataName("child", schema, Catalog: catalog);
                var parentIdentity = new MetadataName("parent", parentSchema, Catalog: catalog);
                var options = new DiscoveryOptions
                {
                    Catalogs = [catalog], Schemas = [schema], Tables = [childIdentity], IncludeReferencedTables = true,
                    Features = [SchemaFeature.Tables, SchemaFeature.Columns, SchemaFeature.PrimaryKeys, SchemaFeature.ForeignKeys,
                        SchemaFeature.Defaults, SchemaFeature.Generation, SchemaFeature.Checks],
                };
                ISchemaMetadataReader reader = new DatabricksMetadataReader();
                var metadata = await reader.ReadAsync(connection, options);
                Assert.That(metadata.Tables.Select(table => table.Identity), Is.EquivalentTo(new[] { childIdentity, parentIdentity }));
                var mapped = metadata.Tables.Single(table => table.Identity == childIdentity);
                Assert.That(mapped.Columns.Select(column => column.Name),
                    Is.EqualTo(new[] { "id", "ref_a", "ref_b", "omitted", "explicit_null", "local_stamp", "note", "folded" }));
                var key = mapped.ForeignKeys.Single();
                Assert.That(key.Target, Is.EqualTo(parentIdentity));
                Assert.That(key.Columns, Is.EqualTo(new[] { "ref_b", "ref_a" }));
                Assert.That(key.TargetColumns, Is.EqualTo(new[] { "b", "a" }));
                Assert.That(metadata.Tables.Single(table => table.Identity == parentIdentity).PrimaryKey!.Columns,
                    Is.EqualTo(new[] { "b", "a" }));
                Assert.That(mapped.Columns.Single(column => column.Name == "omitted").Default, Is.Null);
                Assert.That(mapped.Columns.Single(column => column.Name == "explicit_null").Default, Is.SameAs(DBNull.Value));
                Assert.That(mapped.Columns.Single(column => column.Name == "local_stamp").Default,
                    Is.EqualTo(ColumnDefaultExpression.CurrentTimestamp()));
                Assert.That(mapped.Columns.Single(column => column.Name == "id").Generation, Is.EqualTo(new MetadataGeneration(20, -2)));
                var generated = mapped.Columns.Single(column => column.Name == "folded").Generation;
                Assert.That(generated?.Stored, Is.True);
                Assert.That(generated!.Expression?.Name, Is.EqualTo("Lower"));
                Assert.That(generated.Expression?.Arguments?.Single(), Is.EqualTo(new MetadataExpression("column", "note")));
                Assert.That(mapped.Checks.Single().Name, Is.EqualTo("ordered_check"));
                Assert.That(metadata.Diagnostics.Select(diagnostic => diagnostic.Feature),
                    Is.EquivalentTo(new[] { SchemaFeature.PrimaryKeys, SchemaFeature.ForeignKeys, SchemaFeature.Checks }));

                var inspector = new SchemaInspector();
                Assert.That(inspector.Map(metadata, options).IsSuccess, Is.False);
                var partial = inspector.Map(metadata, options with { AllowPartial = true });
                Assert.That(partial.IsSuccess, Is.True);
                Assert.That(partial.IsComplete, Is.False);
                Assert.That(partial.Schema!.Tables.Count, Is.EqualTo(2));

                var identityOptions = options with
                {
                    Tables = [new("unselected", schema, Catalog: catalog)],
                    IncludeReferencedTables = false,
                    Features = [SchemaFeature.Tables, SchemaFeature.Columns, SchemaFeature.Generation],
                };
                var unsupported = await reader.ReadAsync(connection, identityOptions);
                Assert.That(unsupported.Tables.Single().Columns.Single().Generation, Is.Null);
                Assert.That(unsupported.Diagnostics.Single().Coverage, Is.EqualTo(MetadataCoverage.Unrepresentable));
            }
            finally
            {
                SparkSchemaQa.Execute(connection, $"DROP TABLE IF EXISTS {child}");
                SparkSchemaQa.Execute(connection, $"DROP SCHEMA IF EXISTS {parentScope} CASCADE");
            }
        });
    }

    [Test]
    public Task RestrictedPrincipalSeesViewInventoryAndAnInaccessibleForeignKeyTarget()
    {
        var token = Environment.GetEnvironmentVariable("DATABRICKS_RESTRICTED_TOKEN");
        if (string.IsNullOrWhiteSpace(token))
            Assert.Ignore("Set DATABRICKS_RESTRICTED_TOKEN for a second, non-admin warehouse principal.");
        var owner = OwnerUrl;
        var restricted = new ConnectionUrl(DatabricksWarehouse.Url)
            .WithAuthentication(ConnectionAuthentication.UsernamePassword("token", token!));
        return SparkSchemaQa.WithScratchAsync(owner, async (connection, catalog, schema) =>
        {
            using var readerConnection = (DbConnection)restricted.Open();
            var restrictedPrincipal = (string)SparkSchemaQa.Scalar(readerConnection, "SELECT session_user()")!;
            Assert.That(restrictedPrincipal, Is.Not.EqualTo(SparkSchemaQa.Scalar(connection, "SELECT session_user()")));
            var quote = owner.Dialect.SchemaSqlRenderer;
            string Identifier(string name) => quote.RenderIdentifier(owner.Dialect, name);
            string Name(string table) => quote.RenderObjectName(owner.Dialect, catalog, null, schema, table);
            var principal = Identifier(restrictedPrincipal);
            var parent = Name("hidden_parent");
            var child = Name("visible_child");
            var view = Name("visible_view");
            SparkSchemaQa.Execute(connection, $"CREATE TABLE {parent} (id BIGINT NOT NULL PRIMARY KEY) USING DELTA");
            SparkSchemaQa.Execute(connection, $"CREATE TABLE {child} (id BIGINT, "
                + $"CONSTRAINT hidden_fk FOREIGN KEY (id) REFERENCES {parent} (id)) USING DELTA");
            SparkSchemaQa.Execute(connection, $"CREATE VIEW {view} AS SELECT id FROM {child}");
            SparkSchemaQa.Execute(connection, $"GRANT USE SCHEMA ON SCHEMA {Identifier(catalog)}.{Identifier(schema)} TO {principal}");
            SparkSchemaQa.Execute(connection, $"GRANT SELECT ON TABLE {child} TO {principal}");
            SparkSchemaQa.Execute(connection, $"GRANT SELECT ON VIEW {view} TO {principal}");

            var options = new DiscoveryOptions
            {
                Catalogs = [catalog], Schemas = [schema], IncludeReferencedTables = true,
                Features = [SchemaFeature.Tables, SchemaFeature.Columns, SchemaFeature.ForeignKeys, SchemaFeature.Views],
            };
            var reader = new DatabricksMetadataReader();
            var metadata = await reader.ReadAsync(readerConnection, options);
            Assert.That(metadata.Tables.Single().Identity.Name, Is.EqualTo("visible_child"));
            Assert.That(metadata.Tables.Single().ForeignKeys, Is.Empty);
            Assert.That(metadata.Views.Single().Identity.Name, Is.EqualTo("visible_view"));
            Assert.That(metadata.Views.Single().Projections, Is.Null);
            Assert.That(metadata.Coverage[SchemaFeature.Views], Is.EqualTo(MetadataCoverage.Inaccessible));
            Assert.That(metadata.Coverage[SchemaFeature.ForeignKeys], Is.EqualTo(MetadataCoverage.Inaccessible));
            var inspector = new SchemaInspector();
            Assert.That(inspector.Map(metadata, options).IsSuccess, Is.False);
            var partial = inspector.Map(metadata, options with { AllowPartial = true });
            Assert.That(partial.IsSuccess, Is.True);
            Assert.That(partial.ViewInventory.Single().Identity.Name, Is.EqualTo("visible_view"));
        });
    }
}
